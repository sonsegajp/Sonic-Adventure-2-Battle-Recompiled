# The programs' icon.
#   res/sa2b.ico (committed): a gold ring over a blue/red split - the hero and dark sides - on a dark
#     rounded square. Our own artwork, drawn here; the fallback.
#   --disc <iso>: build/icon/sa2b.ico from the game's own art on the user's disc - Sonic's lives icon
#     (zanki_sonic.GVR, 32x32) as it is, its pixels enlarged whole for the large sizes. Never
#     committed: the build uses it when present.
#   python tools/launcher/mkicon.py [--disc <iso>]  (with Pillow and NumPy)
import math
import os

import numpy as np
from PIL import Image

ROOT = os.path.join(os.path.dirname(__file__), '..', '..')
N = 1024  # drawn large, scaled down for each size


def icon():
    y, x = np.mgrid[0:N, 0:N].astype(np.float32) + 0.5
    u, v = x / N - 0.5, y / N - 0.5
    img = np.zeros((N, N, 4), np.float32)
    # rounded square
    r, half = 0.18, 0.47
    qx, qy = np.maximum(np.abs(u) - (half - r), 0), np.maximum(np.abs(v) - (half - r), 0)
    sq = np.clip((r - np.hypot(qx, qy)) * N / 1.5, 0, 1)
    # blue (upper left) / red (lower right), split along the diagonal with a soft bright seam
    d = (u - v) / math.sqrt(2)  # >0 lower right... (x grows right, y down)
    t = np.clip(0.5 + d * 6, 0, 1)
    blue, red = np.array([0.05, 0.28, 0.85]), np.array([0.80, 0.08, 0.12])
    base = blue * (1 - t[..., None]) + red * t[..., None]
    shade = 0.55 + 0.45 * np.clip(1.2 - np.hypot(u + 0.15, v + 0.2) * 1.6, 0, 1)
    col = base * shade[..., None] + np.exp(-(d * 40) ** 2)[..., None] * 0.35
    # gold ring: a torus seen face-on, its tube shaded as metal lit from the upper left
    rad, thick = 0.25, 0.062
    dist = np.hypot(u, v)
    ring = np.clip((thick - np.abs(dist - rad)) * N / 1.5, 0, 1)
    nr = np.clip((dist - rad) / thick, -1, 1)  # across the tube: -1 inner edge .. 1 outer edge
    nz = np.sqrt(np.clip(1 - nr ** 2, 0, 1))
    ca, sa = u / np.maximum(dist, 1e-6), v / np.maximum(dist, 1e-6)
    n = np.stack([ca * nr, sa * nr, nz], -1)
    L = np.array([-0.55, -0.65, 0.75]); L /= np.linalg.norm(L)
    diff = np.clip((n * L).sum(-1), 0, 1)
    H = L + np.array([0, 0, 1.0]); H /= np.linalg.norm(H)
    spec = np.clip((n * H).sum(-1), 0, 1) ** 40
    base = np.array([1.0, 0.72, 0.12])
    gold = base * (0.22 + 0.9 * diff[..., None]) + spec[..., None] * np.array([1.0, 0.97, 0.8]) * 1.1
    # dark outline under the ring
    outline = np.clip((thick + 0.016 - np.abs(dist - rad)) * N / 1.5, 0, 1)
    col = col * (1 - outline[..., None] * 0.85)
    col = col * (1 - ring[..., None]) + np.clip(gold, 0, 1) * ring[..., None]
    img[..., :3] = np.clip(col, 0, 1)
    img[..., 3] = sq
    return Image.fromarray((img * 255 + 0.5).astype(np.uint8), 'RGBA')


def disc_icon(iso):
    import sys
    sys.path.insert(0, os.path.join(ROOT, 'tools', 'launcher'))  # (gvr.py)
    sys.path.insert(0, os.path.join(ROOT, 'tools'))
    import build_pack
    import gvr
    d = build_pack.Disc(iso)
    path, off, size = next(f for f in d.files() if f[0].lower() == 'zanki_sonic.gvr')
    _, fmt, w, h, small = next(gvr.textures(d.read(off, size)))
    out = os.path.join(ROOT, 'build', 'icon')
    os.makedirs(out, exist_ok=True)
    pix = Image.fromarray(small)  # its own pixels: whole multiples up (crisp), smoothly down
    frames = [pix.resize((n, n), Image.LANCZOS) if n < 32 else pix for n in (16, 24, 32)]
    frames += [pix.resize((64, 64), Image.NEAREST).resize((48, 48), Image.LANCZOS)]
    frames += [pix.resize((n, n), Image.NEAREST) for n in (64, 128, 256)]
    frames[-1].save(os.path.join(out, 'sa2b.ico'), sizes=[f.size for f in frames], append_images=frames[:-1])
    frames[-1].save(os.path.join(out, 'sa2b_icon.png'))
    with open(os.path.join(out, 'sa2b.rc'), 'w', newline='\n') as f:
        f.write('// Generated by tools/launcher/mkicon.py --disc (from the disc: never committed).\n1 ICON "sa2b.ico"\n')
    print('build/icon/sa2b.ico')


import sys as _sys
if '--disc' in _sys.argv:
    disc_icon(_sys.argv[_sys.argv.index('--disc') + 1])
    raise SystemExit
big = icon()
out = os.path.join(ROOT, 'res')
os.makedirs(out, exist_ok=True)
big.resize((256, 256), Image.LANCZOS).save(os.path.join(out, 'sa2b.ico'), sizes=[(16, 16), (24, 24), (32, 32), (48, 48), (64, 64), (128, 128), (256, 256)])
big.resize((256, 256), Image.LANCZOS).save(os.path.join(out, 'sa2b_icon.png'))
print('res/sa2b.ico')
