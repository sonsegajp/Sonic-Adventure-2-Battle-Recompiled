# Renders the launcher's button labels and its two no-disc messages to src/launcher/labels.inc.
#
# The game's own button labels are prerendered textures in a chunky extended face; the launcher's
# new ones (PLAY, SETTINGS, ...) are rendered here in Vipnagorgialla (Typodermic), which matches
# it. Typodermic's desktop licence allows rendered artwork but not shipping the font or a reusable
# character set, so only whole words and sentences are rendered - never single letters - and the
# font file itself stays out of the repository and the program.
#
# Each image is an 8-bit coverage mask, run-length coded as (run length - 1, value) byte pairs;
# the launcher adds the colours, outline and shadow when it builds the textures.
#   tools/hd/venv/Scripts/python tools/launcher/mklabels.py <folder with the Vipnagorgialla .otf files>
import os
import sys

from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.join(os.path.dirname(__file__), '..', '..')
FONT_DIR = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, 'build', 'launcher_assets', 'font')

# (id, text, face, size in pixels): buttons at twice the launcher's 720-line layout
LABELS = [
    ('play', 'PLAY', 'Bd', 92),
    ('settings', 'SETTINGS', 'Bd', 92),
    ('hdtex', 'HD TEXTURES', 'Bd', 92),
    ('mods', 'MODS', 'Bd', 92),
    ('quit', 'QUIT', 'Bd', 92),
    ('choosedisc', 'CHOOSE DISC', 'Bd', 92),
    ('back', 'BACK', 'Bd', 92),
    ('setup', 'SETUP', 'Bd', 92),
    ('coop', 'CO-OP', 'Bd', 92),
    ('cancel', 'CANCEL', 'Bd', 92),
    ('tryagain', 'TRY AGAIN', 'Bd', 92),
    ('nodisc', 'Choose your Sonic Adventure 2: Battle disc image to begin.', 'Rg', 44),
    ('wrongdisc', 'That file is not Sonic Adventure 2: Battle (USA). Choose another.', 'Rg', 44),
]


def render(text, face, size):
    font = ImageFont.truetype(os.path.join(FONT_DIR, f'Vipnagorgialla {face}.otf'), size)
    l, t, r, b = font.getbbox(text)
    pad = size // 6
    im = Image.new('L', (r - l + 2 * pad, b - t + 2 * pad), 0)
    ImageDraw.Draw(im).text((pad - l, pad - t), text, font=font, fill=255)
    return im


def rle(data):
    out = bytearray()
    i = 0
    while i < len(data):
        v = data[i]
        n = 1
        while i + n < len(data) and n < 256 and data[i + n] == v:
            n += 1
        out += bytes((n - 1, v))
        i += n
    return bytes(out)


lines = ['// Generated by tools/launcher/mklabels.py: rendered words, not a font (see there).',
         '// {id, width, height, run-length coded coverage, its size}']
table = []
for ident, text, face, size in LABELS:
    im = render(text, face, size)
    data = rle(im.tobytes())
    name = f'kLabel_{ident}'
    lines.append(f'static const unsigned char {name}[{len(data)}] = {{')
    for k in range(0, len(data), 32):
        lines.append('    ' + ','.join(str(x) for x in data[k:k + 32]) + ',')
    lines.append('};')
    table.append(f'    {{"{ident}", {im.width}, {im.height}, {name}, {len(data)}}},')
    print(f'{ident}: {im.width}x{im.height}, {len(data)} bytes')
lines.append('static const LabelImage kLabels[] = {')
lines += table
lines.append('};')
with open(os.path.join(ROOT, 'src', 'launcher', 'labels.inc'), 'w', newline='\n') as f:
    f.write('\n'.join(lines) + '\n')
