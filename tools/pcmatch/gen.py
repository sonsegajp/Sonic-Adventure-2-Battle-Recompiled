for pa, gs in sorted(pairs.items()):
    rep = gs[0]
    if rep not in gf: continue
    a, b = pc_tokens(pa), gc_tokens(rep)
    if not a or not b: continue
    main, imm = collections.defaultdict(set), collections.defaultdict(set)
    for i, j in pair_tokens(a, b):
        at, t = a[i]
        (imm if t[0] in ('c', 'p') else main)[at].add(b[j][0])
    for at in sorted(set(main) | set(imm)):
        if at in callsite_pcs: continue
        ins = pc_insn(at)
        if ins is None or ins.mnemonic in ('call', 'jmp') or ins.mnemonic.startswith('j'): continue
        ms = sorted(main.get(at, ())); ims = sorted(imm.get(at, ()))
        if len(ms) > 1 or len(ims) > 1: continue  # one PC instruction, one GameCube one
        main_sites = sites_for(gs, rep, ms[0]) if ms else []
        imm_sites = sites_for(gs, rep, ims[0]) if ims else []
        if not main_sites and not imm_sites: continue
        line = 'insn %08X %s %s' % (at, bytes(ins.bytes).hex(), ','.join(main_sites or imm_sites))
        if main_sites and imm_sites: line += ' imm=' + ','.join(imm_sites)
        elif imm_sites: line += ' imm=' + ','.join(imm_sites)
        lines.append(line)
        ni += 1
        # the conditional jump after a compare
        if ins.mnemonic in ('cmp', 'test'):
            nxt = pc_insn(at + ins.size)
            if nxt is None or nxt.mnemonic not in CC or (at + ins.size) in callsite_pcs: continue
            g0 = (ims or ms)[0]
            br = gc_branch_after(g0, gf[rep]['end'])
            if not br: continue
            ba, gtaken, sgn = br
            cc = CC[nxt.mnemonic]
            if cc in (2, 3, 6, 7) and sgn or cc in (12, 13, 14, 15) and not sgn: continue
            xt = x86_taken(cc)
            if xt == gtaken: inv = ''
            elif (7 & ~xt) == gtaken: inv = ' inv'
            else: continue
            bs = sites_for(gs, rep, ba)
            if bs:
                lines.append('insn %08X %s %s%s' % (nxt.address, bytes(nxt.bytes).hex(), ','.join(bs), inv))
                nj += 1

