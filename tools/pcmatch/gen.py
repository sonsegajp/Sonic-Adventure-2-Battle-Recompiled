FLOATS = ('float', 'double')
def signature(s):
    """GameCube argument registers from x86 sources, for a header-declared function."""
    conv, args = s['conv'], s['args']
    out, gi, fi, slot = [], 3, 1, 0
    regs = []
    if conv == 'thiscall': regs = ['ecx']
    elif conv == 'fastcall': regs = ['ecx', 'edx']
    for t in args:
        t0 = t.replace(' ', '')
        isf = t0 in FLOATS
        if isf:
            out.append('f%d=s%d' % (fi, slot)); fi += 1
            slot += 2 if t0 == 'double' else 1
            continue
        if regs:
            out.append('r%d=%s' % (gi, regs.pop(0))); gi += 1
            continue
        out.append('r%d=s%d' % (gi, slot)); gi += 1; slot += 1
    ret = s['ret'].replace(' ', '')
    opts = []
    if ret in FLOATS: opts.append('ret=st0')
    elif ret not in ('void', ''): opts.append('ret=eax')
    if conv in ('stdcall', 'thiscall', 'fastcall'): opts.append('pop=%d' % (4 * slot))
    return (','.join(out) or '-'), opts

