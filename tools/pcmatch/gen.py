def gc_is_ptr(v): return any(a0 <= v < a1 for a0, a1 in GREG)
LAYOUTS = ((4,), (2, 2), (1, 1, 1, 1), (2, 1, 1), (1, 1, 2))
def word_layouts(pa, ga, blk):
    # The layouts under which PC word pa holds GameCube word ga's values; 'ptr' for pointers.
    s0, d = blk
    if not (PCDATA[0] <= pa < PCDATA[1]) or not (s0 <= ga and ga + 4 <= s0 + len(d)): return ()
    p, g = pcbytes(pa, 4), d[ga - s0:ga - s0 + 4]
    if len(p) < 4: return ()
    if pa in PCRELOC: return ('ptr',) if gc_is_ptr(struct.unpack('>I', g)[0]) else ()
    if gc_is_ptr(struct.unpack('>I', g)[0]) and any(p): return ()
    out = []
    for lay in LAYOUTS:
        o = 0
        for e in lay:
            if p[o:o + e] != g[o:o + e][::-1]: break
            o += e
        else: out.append(lay)
    return tuple(out)
def is_dbl(q, r, blk):
    s0, d = blk
    return (s0 <= r and r + 8 <= s0 + len(d) and PCDATA[0] <= q < PCDATA[1] and any(pcbytes(q, 8))
            and pcbytes(q, 8) == bytes(d[r - s0:r - s0 + 8][::-1]))
def strong(p, g, step, blk, n=4):
    """The n words from (p, g) on agree, at least two of them telling (not zeros)."""
    told = 0
    for i in range(n):
        c = word_layouts(p + 4 * i * step, g + 4 * i * step, blk)
        if not c: return False
        told += c != LAYOUTS
    return told >= 2
def walk(pa, ga, step):
    """(PC word, GameCube word, layouts) from the matched pair on in one direction. The builds'
    tables are not always the same: a changed value ('sub', laid out as its column) or a row one side
    has more is stepped over when the words after it agree again."""
    blk = gc_block(ga)
    if not blk: return []
    out, zeros, resyncs = [], 0, 0
    p, g = (pa, ga) if step > 0 else (pa - 4, ga - 4)
    for _ in range(2048):
        c = word_layouts(p, g, blk)
        if c:
            zeros = zeros + 1 if c == LAYOUTS else 0
            if zeros >= 16: break  # a stretch of zeros: past the table
            out.append((p, g, c))
            p += 4 * step; g += 4 * step
            continue
        q, r = (p, g) if step > 0 else (p - 4, g - 4)
        if is_dbl(q, r, blk):
            out += [(q, r, 'dbl'), (q + 4, r + 4, 'dbl2')]
            p += 8 * step; g += 8 * step; zeros = 0
            continue
        if resyncs >= 8: break
        resyncs += 1
        for sub in (1, 2):
            if strong(p + 4 * sub * step, g + 4 * sub * step, step, blk):
                for i in range(sub): out.append((p + 4 * i * step, g + 4 * i * step, 'sub'))
                p += 4 * sub * step; g += 4 * sub * step
                break
        else:
            for k in range(1, 17):
                if strong(p + 4 * k * step, g, step, blk): p += 4 * k * step; break  # PC has more
                if strong(p, g + 4 * k * step, step, blk): g += 4 * k * step; break  # GameCube has more
            else: break
    while out and out[-1][2] in (LAYOUTS, 'sub'): out.pop()  # trailing zeros are not evidence
    return out
def resolve(words):
    # One layout per word, by column consensus (columns of the PC table).
    p0 = min(w[0] for w in words)
    idx = [(w[0] - p0) // 4 for w in words]
    n = max(idx) + 1
    cand = [w[2] for w in words]
    pref = collections.Counter(c[0] for c in cand if isinstance(c, tuple) and len(c) == 1)
    order = sorted(LAYOUTS, key=lambda l: (-pref[l], LAYOUTS.index(l)))
    def pick(s): return next(l for l in order if l in s)
    def free(c): return c in ('dbl', 'dbl2', 'sub') or c == ('ptr',)
    best = None
    for P in range(1, min(32, max(1, n // 2)) + 1):
        inter, cost = [None] * P, 0
        for i, c in zip(idx, cand):
            if free(c): continue
            k = i % P
            inter[k] = set(c) if inter[k] is None else inter[k] & set(c)
        for x in inter:
            if x is not None and not x: cost += 5
            elif x: cost += len(x) - 1
        if best is None or cost < best[0]: best = (cost, P, inter)
    if best is None: best = (0, 1, [None])
    _, P, cols = best
    out = []
    for i, c in zip(idx, cand):
        if c in ('dbl', 'dbl2'): out.append(c)
        elif c == ('ptr',): out.append('ptr')
        elif cols[i % P]: out.append(pick(cols[i % P]))
        else: out.append(pick(set(LAYOUTS if c == 'sub' else c)))
    return out
