def pair_tokens(a, b):
    ca = collections.Counter(t for _, t in a); cb = collections.Counter(t for _, t in b)
    out = [(i, j) for i, (_, t) in enumerate(a) for j, (_, u) in enumerate(b) if t == u and ca[t] == 1 and cb[t] == 1]
    if len(a) * len(b) <= 160000:
        done_a = {i for i, _ in out}; done_b = {j for _, j in out}
        for i, j in lcs(a, b, lambda x, y: x[1] == y[1]):
            if i not in done_a and j not in done_b and ca[a[i][1]] > 1: out.append((i, j))
    return out
def masked(w):
    # an instruction with what linking changes masked (copies of a function compare equal)
    op = w >> 26
    if op == 18: return w & 0xFC000003
    if op == 16: return w & 0xFFFF0003
    if op in (14, 15, 24, 25) or 32 <= op <= 55: return w & 0xFFFF0000
    return w
def sites_for(gs, rep, ga):
    off = ga - rep
    w0 = GAME.u32(ga)
    out = []
    for g in gs:
        w = GAME.u32(g + off)
        if w is None or masked(w) != masked(w0): continue
        r = gc_ref(g + off)
        if r: out.append(r)
    return out
CC = {'jb': 2, 'jae': 3, 'je': 4, 'jne': 5, 'jbe': 6, 'ja': 7, 'jl': 12, 'jge': 13, 'jle': 14, 'jg': 15}
LT, GT, EQ = 1, 2, 4
def x86_taken(cc):
    return {2: LT, 3: GT | EQ, 4: EQ, 5: LT | GT, 6: LT | EQ, 7: GT, 12: LT, 13: GT | EQ, 14: LT | EQ, 15: GT}[cc]
def gc_compare(w):
    # (crf, signed?) of a compare instruction, else None
    op = w >> 26
    if op == 11: return (w >> 23) & 7, True
    if op == 10: return (w >> 23) & 7, False
    if op == 31 and ((w >> 1) & 0x3FF) in (0, 32): return (w >> 23) & 7, ((w >> 1) & 0x3FF) == 0
    return None
def gc_branch_after(ga, end):
    # the compare at or shortly after ga, and the conditional branch testing it: (bc address, taken set, signed)
    for k in range(0, 6):
        w = GAME.u32(ga + 4 * k)
        if w is None or ga + 4 * k >= end: return None
        c = gc_compare(w)
        if not c: continue
        crf, sgn = c
        for m in range(k + 1, k + 9):
            a = ga + 4 * m
            if a >= end: return None
            x = GAME.u32(a)
            if x is None: return None
            if gc_compare(x) and gc_compare(x)[0] == crf: return None
            op = x >> 26
            if op == 18 or (op == 19 and ((x >> 1) & 0x3FF) in (16, 528)): return None  # flow leaves
            if op == 16:
                bo, bi = (x >> 21) & 31, (x >> 16) & 31
                if (bo & 0x14) != 0x04 or bi >> 2 != crf: continue
                bit = 1 << (bi & 3)
                taken = bit if bo & 8 else (15 & ~bit)
                return a, taken & 7, sgn
        return None
    return None
